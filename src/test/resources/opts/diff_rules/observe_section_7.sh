#!/bin/bash
# Records what the CLI (SDK version it is built with) reports for every pair of section_7_pairing/.
# Usage: observe_section_7.sh [path to openehr CLI]   -> writes section_7_pairing/OBSERVED.md
CLI=${1:-/home/pablo/GitHub/openEHR-CLI/app/build/install/openehr/bin/openehr}
cd "$(dirname "$0")/section_7_pairing" || exit 1
{
  echo "# Observed diff output (section 7 fixtures)"; echo
  echo "Generated by observe_section_7.sh with the CLI as built (see opt_diff_rules.md section 7). Not an expectation: it records what the SDK reports today."; echo
  for f in *_v0.opt; do c=${f%_v0.opt}
    echo "## $c"; echo '```'
    $CLI diff --old ${c}_v0.opt --new ${c}_v1.opt --no-color 2>&1 | sed -n '/^~ \//,$p'
    echo '```'; echo
  done
} > OBSERVED.md
